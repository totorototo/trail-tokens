// tokens.json → theme.js: the object every app's src/theme/Theme.js exported by hand.
// Run with `npm run build`; theme.js is committed, and CI fails when it is stale.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const tokens = JSON.parse(readFileSync(new URL("tokens.json", root), "utf8"));

const THEMES = tokens.color.themes.map((t) => t.id);
const colorTokens = new Map(tokens.color.tokens.map((t) => [t.name, t]));

// A value is a literal or one `{name}` reference. `{name}` reads the same theme;
// `{name.dark}` / `{name.light}` pins a theme, which the map inks need: the basemap
// stays light in dark mode, so they take one theme's colour in both.
const REF = /^\{([a-z0-9-]+)(?:\.([a-z]+))?\}$/;

function resolve(name, theme, seen = []) {
  if (seen.includes(`${name}.${theme}`)) {
    throw new Error(`Reference cycle: ${[...seen, `${name}.${theme}`].join(" → ")}`);
  }
  const token = colorTokens.get(name);
  if (!token) throw new Error(`Unknown token {${name}} (from ${seen.at(-1) ?? "?"})`);
  const value = token.value[theme];
  if (value === undefined) throw new Error(`${name} has no ${theme} value`);
  const ref = REF.exec(value);
  if (!ref) return value;
  const [, target, pinned] = ref;
  if (pinned && !THEMES.includes(pinned)) {
    throw new Error(`${name}.${theme}: unknown theme "${pinned}" in ${value}`);
  }
  return resolve(target, pinned ?? theme, [...seen, `${name}.${theme}`]);
}

const MAP_PREFIX = "map-";
const COLOR_PREFIX = "color-";

const colors = Object.fromEntries(
  THEMES.map((theme) => [
    theme,
    Object.fromEntries(
      [...colorTokens.keys()]
        .filter((name) => name.startsWith(COLOR_PREFIX))
        .map((name) => [`--${name}`, resolve(name, theme)]),
    ),
  ]),
);

// The map inks are theme-independent by design; refuse a token that disagrees.
const map = Object.fromEntries(
  [...colorTokens.keys()]
    .filter((name) => name.startsWith(MAP_PREFIX))
    .map((name) => {
      const [first, ...rest] = THEMES.map((theme) => resolve(name, theme));
      if (rest.some((v) => v !== first)) {
        throw new Error(`${name} differs between themes; map inks must be one colour`);
      }
      return [name.slice(MAP_PREFIX.length), first];
    }),
);

const customProperties = (group) =>
  Object.fromEntries(tokens[group].tokens.map((t) => [`--${t.name}`, t.value]));

// The 4px grid (`space-*`), as custom properties; measure and touch-target go out with the
// layout tokens.
const space = Object.fromEntries(
  tokens.spacing.tokens
    .filter((t) => t.name.startsWith("space-"))
    .map((t) => [`--${t.name}`, t.value]),
);

// The doubling scale Terminus reads as theme.spacing[n] (px), from before the 4px grid.
// why frozen here, not in tokens.json: it is no longer the design system's scale, only what
// Terminus's styles still index; it goes when Terminus moves to theme.space.
const LEGACY_SPACING = [0, 2, 4, 8, 16, 32, 64, 128, 256];

const spacingToken = (name) => {
  const token = tokens.spacing.tokens.find((t) => t.name === name);
  if (!token) throw new Error(`Missing ${name}`);
  return token.value;
};

const FAMILY_KEYS = { sans: "--font-family-sansSerif", mono: "--font-family-mono" };

const THEME = {
  colors,
  map,
  font: {
    family: Object.fromEntries(
      Object.entries(tokens.type.families).map(([id, value]) => {
        if (!FAMILY_KEYS[id]) throw new Error(`No Theme.js key for font family "${id}"`);
        return [FAMILY_KEYS[id], value];
      }),
    ),
    weights: customProperties("fontWeight"),
    sizes: customProperties("fontSize"),
  },
  borderRadius: customProperties("radius"),
  zIndex: customProperties("zIndex"),
  transitions: customProperties("motion"),
  layout: {
    ...customProperties("layout"),
    "--measure": spacingToken("measure"),
    "--touch-target": spacingToken("touch-target"),
  },
  space,
  spacing: LEGACY_SPACING,
  breakpoints: ["sm", "md", "lg"].map((size) => {
    const token = tokens.breakpoint.tokens.find((t) => t.name === `breakpoint-${size}`);
    if (!token) throw new Error(`Missing breakpoint-${size}`);
    return token.value;
  }),
};

const source = `// Generated by scripts/build.mjs from tokens.json — do not edit.
// Trail Suite design system, artifact version ${tokens.meta.artifact.version} (synced ${tokens.meta.synced}).
const THEME = ${JSON.stringify(THEME, null, 2)};

export default THEME;
`;

writeFileSync(new URL("theme.js", root), source);
